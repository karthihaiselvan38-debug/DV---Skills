import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

df = pd.read_csv("/kc_house_data.csv")
df

df.head()

df.tail()

df.info()

df.describe()

df.shape

df.columns

df.isnull().sum()

df['date'] = pd.to_datetime(
    df['date'],
    format='%Y%m%dT%H%M%S')


df['date'].head()

df["sale_year"] = df["date"].dt.year
df["sale_month"] = df["date"].dt.month
df["sale_day"] = df["date"].dt.day
df["sale_hour"] = df["date"].dt.hour

df[["sale_year", "sale_month", "sale_day", "sale_hour"]].head()

df["bedrooms"] = df["bedrooms"].replace(0, df["bedrooms"].median())
df["bathrooms"] = df["bathrooms"].replace(0, df["bathrooms"].median())

df["property_age"] = df["sale_year"] - df["yr_built"]

df["is_renovated"] = df["yr_renovated"].apply(lambda x: 1 if x > 0 else 0)

df["years_since_renovation"] = df.apply(
    lambda row: row["sale_year"] - row["yr_renovated"]
    if row["yr_renovated"] > 0
    else row["property_age"],
    axis=1,
)

df["price_per_sqft_living"] = df["price"] / df["sqft_living"]
df["price_per_sqft_lot"] = df["price"] / df["sqft_lot"]

Q1 = df["price"].quantile(0.25)
Q3 = df["price"].quantile(0.75)
IQR = Q3 - Q1
lower_bound = Q1 - 1.5 * IQR
upper_bound = Q3 + 1.5 * IQR

outliers = df[(df["price"] < lower_bound) | (df["price"] > upper_bound)]
print(f"Number of price outliers identified: {len(outliers)}")

plt.figure(figsize=(8, 4))
sns.boxplot(x=df["price"])
plt.title("Box Plot of House Prices (Outlier Detection)")
plt.show()