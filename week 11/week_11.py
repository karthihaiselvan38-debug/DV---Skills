import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
import kagglehub
import os
import glob

path = kagglehub.dataset_download("toramky/automobile-dataset")

csv_files = glob.glob(os.path.join(path, "*.csv"))

print("Available CSV Files:", csv_files)

df = pd.read_csv(csv_files[0])

print("First Five Records:")
display(df.head())

print("Last Five Records:")
display(df.tail())

print("Dataset Dimensions:")
print("Number of Rows:", df.shape[0])
print("Number of Columns:", df.shape[1])

print("Column Names:")
print(df.columns.tolist())

print("Dataset Information:")
df.info()

print("\nStatistical Summary:")
display(df.describe())

print("\nCategorical Columns:")
categorical_columns = [
    "make",
    "fuel-type",
    "body-style",
    "drive-wheels",
    "engine-location"
]

display(df[categorical_columns].describe())

print("\nNumerical Columns:")
numerical_columns = [
    "engine-size",
    "horsepower",
    "peak-rpm",
    "curb-weight",
    "city-mpg",
    "highway-mpg",
    "price"
]

display(df[numerical_columns].describe())

print("Searching for '?' values:")

for column in df.columns:
    count = (df[column].astype(str).str.strip() == "?").sum()
    if count > 0:
        print(column, ":", count)

df.replace("?", np.nan, inplace=True)

print("\nMissing Values in Each Column:")
display(df.isnull().sum())

print("\nMissing Value Percentage:")
missing_percentage = (df.isnull().sum() / len(df)) * 100
display(missing_percentage.sort_values(ascending=False))

print("\nColumns with High Missing Values:")
display(missing_percentage[missing_percentage > 20])

selected_columns = [
    "horsepower",
    "peak-rpm",
    "bore",
    "stroke",
    "price"
]

for column in selected_columns:
    df[column] = pd.to_numeric(df[column], errors="coerce")

categories = [
    "make",
    "body-style",
    "fuel-type"
]

for column in selected_columns:
    for category in categories:
        category_median = df.groupby(category, dropna=False)[column].transform("median")
        df[column] = df[column].fillna(category_median)

    overall_median = df[column].median()
    df[column] = df[column].fillna(overall_median)

print("Missing Values After Imputation:")
display(df[selected_columns].isnull().sum())

print("\nUpdated Dataset:")
display(df.head())

df["horsepower"] = pd.to_numeric(df["horsepower"], errors="coerce")
df["peak-rpm"] = pd.to_numeric(df["peak-rpm"], errors="coerce")
df["price"] = pd.to_numeric(df["price"], errors="coerce")
df["bore"] = pd.to_numeric(df["bore"], errors="coerce")
df["stroke"] = pd.to_numeric(df["stroke"], errors="coerce")

df["engine-size"] = pd.to_numeric(df["engine-size"], errors="coerce")
df["curb-weight"] = pd.to_numeric(df["curb-weight"], errors="coerce")
df["city-mpg"] = pd.to_numeric(df["city-mpg"], errors="coerce")
df["highway-mpg"] = pd.to_numeric(df["highway-mpg"], errors="coerce")

df["horsepower"] = df["horsepower"].round().astype("Int64")
df["peak-rpm"] = df["peak-rpm"].astype(float)
df["price"] = df["price"].astype(float)
df["bore"] = df["bore"].astype(float)
df["stroke"] = df["stroke"].astype(float)

print("Updated Data Types:")
df.info()

print("\nMissing Values in Converted Columns:")
display(df[
    ["horsepower", "peak-rpm", "price", "bore", "stroke"]
].isnull().sum())

df["power_to_weight_ratio"] = (
    df["horsepower"] / df["curb-weight"]
) * 1000

print("Power-to-Weight Ratio:")
display(
    df[["make", "horsepower", "curb-weight", "power_to_weight_ratio"]].head(10)
)

print("\nComparison Across Automobile Models:")
display(
    df[["make", "power_to_weight_ratio"]]
    .sort_values(by="power_to_weight_ratio", ascending=False)
    .head(10)
)

df["combined_mpg"] = (
    df["city-mpg"] + df["highway-mpg"]
) / 2

print("Combined MPG:")
display(
    df[["make", "city-mpg", "highway-mpg", "combined_mpg"]].head(10)
)

print("\nFuel Efficiency Comparison:")
display(
    df[["make", "combined_mpg"]]
    .sort_values(by="combined_mpg", ascending=False)
    .head(10)
)

body_style_summary = df.groupby("body-style").agg(
    average_horsepower=("horsepower", "mean"),
    average_engine_size=("engine-size", "mean"),
    average_curb_weight=("curb-weight", "mean"),
    average_price=("price", "mean"),
    average_combined_mpg=("combined_mpg", "mean")
)

print("Statistical Summary Across Body Styles:")
display(body_style_summary)

engine_location_summary = df.groupby("engine-location").agg(
    average_horsepower=("horsepower", "mean"),
    average_engine_size=("engine-size", "mean"),
    average_curb_weight=("curb-weight", "mean"),
    average_price=("price", "mean")
)

print("Statistical Summary Across Engine Locations:")
display(engine_location_summary)

print("\nComparison Between Front and Rear Engine Vehicles:")
display(engine_location_summary.loc[
    engine_location_summary.index.isin(["front", "rear"])
])

print("Remaining Missing Values:")
display(df.isnull().sum())

print("\nNumerical Data Types:")
display(df.dtypes)

print("\nDuplicate Records:")
print("Number of Duplicate Rows:", df.duplicated().sum())

print("\nFeature Validation:")
display(
    df[
        [
            "horsepower",
            "curb-weight",
            "power_to_weight_ratio",
            "city-mpg",
            "highway-mpg",
            "combined_mpg"
        ]
    ].head(10)
)

print("\nFinal Dataset Information:")
df.info()

print("\nFinal Dataset Dimensions:")
print(df.shape)

df.to_csv("automobile_cleaned.csv", index=False)

print("\nCleaned Dataset Exported Successfully!")

